begin;
do $$
declare r jsonb;rid bigint;eid bigint;cfg jsonb;g uuid:=gen_random_uuid();ts timestamptz:=date_trunc('minute',now());v jsonb;
begin
 update public.s2a_settings set data=data||'{"ops_monitoring_enabled":true}' where id='11111111-0000-4000-8000-000000000001';
 update public.s2a_ops_alert_rules set enabled=false where enabled;
 r:=public.s2a_ops_alert_rule_save(null,jsonb_build_object('name','Availability','metric_type','group_available_accounts','operator','<','threshold',1,'sustained_minutes',2,'cooldown_minutes',5,'severity','P1','filters',jsonb_build_object('platform','openai','group_id',g)));
 rid:=(r->>'id')::bigint;assert r->>'severity'='P1';assert r->'enabled'='true'::jsonb;
 r:=public.s2a_ops_alert_rule_save(rid,'{"name":"Availability renamed","metric_type":"group_available_accounts","operator":"<","threshold":1}');
 assert (r->>'sustained_minutes')::integer=2 and r->>'severity'='P1','partial updates preserve optionals';
 assert public.s2a_ops_alert_evaluate(ts)->>'created'='0';
 assert public.s2a_ops_alert_evaluate(ts+interval '60 seconds')->>'created'='1';
 select id into eid from public.s2a_ops_alert_events where rule_id=rid and status='firing';
 assert eid is not null;
 assert public.s2a_ops_alert_evaluate(ts+interval '60 seconds')->>'evaluated'='0','same tick is idempotent';
 assert public.s2a_ops_alert_evaluate(ts+interval '120 seconds')->>'created'='0','one active event';
 assert public.s2a_ops_alert_event_get(eid)->'email_sent'='false'::jsonb,'evaluation never claims email delivery';
 assert jsonb_array_length(public.s2a_ops_alert_events_list(jsonb_build_object('group_id',g,'status','firing')))=1;
 assert jsonb_array_length(public.s2a_ops_alert_events_list(jsonb_build_object('before_fired_at',ts+interval '60 seconds','before_id',eid)))=0;
 perform public.s2a_ops_alert_event_status(eid,'manual_resolved');
 assert public.s2a_ops_alert_evaluate(ts+interval '180 seconds')->>'created'='0','cooldown uses fired_at';
 perform public.s2a_ops_alert_silence_create(jsonb_build_object('rule_id',rid,'platform','openai','group_id',g,'until',ts+interval '30 minutes','reason','maintenance'));
 assert public.s2a_ops_alert_evaluate(ts+interval '6 minutes')->>'created'='0','gap resets sustained breaches';
 assert public.s2a_ops_alert_evaluate(ts+interval '7 minutes')->>'created'='0','scoped silence blocks firing';
 delete from public.s2a_ops_alert_silences where rule_id=rid;
 assert public.s2a_ops_alert_evaluate(ts+interval '8 minutes')->>'created'='1';
 -- A missing metric resets breach state and leaves active events untouched.
 r:=public.s2a_ops_alert_rule_save(rid,'{"name":"Missing sample","metric_type":"cpu_usage_percent","operator":">","threshold":90}');
 assert public.s2a_ops_alert_evaluate(ts+interval '9 minutes')->>'resolved'='0';
 assert (select consecutive_breaches from public.s2a_ops_alert_state where rule_id=rid)=0;
 r:=public.s2a_ops_alert_rule_save(rid,'{"name":"Recovered","metric_type":"concurrency_queue_depth","operator":">","threshold":0}');
 assert public.s2a_ops_alert_evaluate(ts+interval '10 minutes')->>'resolved'='1';
 assert (select count(*) from public.s2a_ops_alert_events where rule_id=rid and status='firing')=0;
 cfg:=public.s2a_ops_alert_runtime_get();
 assert cfg->>'evaluation_interval_seconds'='60';
 v:=public.s2a_ops_alert_runtime_set((cfg-'thresholds')||'{"evaluation_interval_seconds":5}');
 assert v->'thresholds'=cfg->'thresholds','runtime does not erase separately configured thresholds';
 assert v->>'evaluation_interval_seconds'='5';
 v:=public.s2a_ops_alert_runtime_set(jsonb_set(cfg,'{thresholds,sla_percent_min}','1'));
 assert v->'thresholds'=cfg->'thresholds','stale runtime snapshot cannot overwrite dedicated metric settings';
 begin perform public.s2a_ops_alert_runtime_set(jsonb_set(cfg,'{distributed_lock,ttl_seconds}','0'));raise exception 'bad ttl accepted';exception when raise_exception then assert sqlerrm='invalid_alert_runtime';end;
 begin perform public.s2a_ops_alert_rule_save(null,'{"name":"Bad","metric_type":"error_rate","operator":">","threshold":101}');raise exception 'bad percentage accepted';exception when check_violation then null;end;
 begin perform public.s2a_ops_alert_rule_save(null,'{"name":"Bad","metric_type":"error_rate","operator":">","threshold":1,"enabled":null}');raise exception 'null flag accepted';exception when raise_exception then assert sqlerrm='invalid_alert_rule';end;
 assert public.s2a_ops_alert_rule_delete(rid)->'deleted'='true'::jsonb;
 assert public.s2a_ops_alert_event_get(eid)->>'error'='alert_event_not_found';
 assert public.s2a_ops_alert_rule_delete(rid)->>'error'='alert_rule_not_found';
 assert not has_function_privilege('service_role','public.s2a_ops_alert_evaluate(timestamptz,integer)','EXECUTE');
 assert not has_table_privilege('service_role','public.s2a_ops_alert_events','INSERT');
 assert not has_function_privilege('authenticated','public.s2a_ops_alert_rules_list()','EXECUTE');
end $$;
rollback;
