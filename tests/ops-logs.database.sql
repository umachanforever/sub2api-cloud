begin;
do $$
declare cfg jsonb; event jsonb; health jsonb; rid text:='ops-log-database-fixture'; n integer; expected bigint;
 actor uuid:='d1000000-0000-4000-8000-000000000001'; gid uuid:='d1000000-0000-4000-8000-000000000002';
 aid uuid:='d1000000-0000-4000-8000-000000000003'; lease uuid; wallet_balance numeric; usage_count bigint;
begin
 cfg:=public.s2a_log_config_get()-array['source','updated_at','updated_by_user_id'];
 assert cfg->>'request_retention_days'='0','usage is retained by default';
 event:=jsonb_build_object('host','supabase-edge','component','edge','level','warn','message','request_failed','request_id',rid,
  'extra',jsonb_build_object('caller','app.dispatch','stacktrace',jsonb_build_array('dispatch'),'status_code',429));
 assert public.s2a_log_write(event),'errors persist without access logs';
 assert not public.s2a_log_write(event||'{"level":"debug"}'),'runtime minimum level applies';
 assert not public.s2a_log_write(event||'{"level":"info","message":"response_started"}'),'access logs default off';
 begin perform public.s2a_log_config_set(cfg||'{"sampling_initial":0}');raise exception 'invalid config accepted';exception when raise_exception then assert sqlerrm='invalid_log_config';end;
 begin perform public.s2a_log_config_set(cfg||'{"unknown":true}');raise exception 'unknown field accepted';exception when raise_exception then assert sqlerrm='invalid_log_config';end;
 perform public.s2a_log_config_set(cfg||'{"level":"error","caller":false,"stacktrace_level":"none"}');
 assert not public.s2a_log_write(event),'changed minimum level takes effect';
 assert public.s2a_log_write(event||'{"level":"error"}');
 assert (select not(extra?'caller') and not(extra?'stacktrace') from public.s2a_system_logs where request_id=rid order by id desc limit 1),'caller/stacktrace options affect persisted data';
 health:=public.s2a_log_health();
 assert not public.s2a_log_write(event||'{"level":"error","user_id":"invalid-uuid"}'),'sink insert failures return false';
 assert (public.s2a_log_health()->>'write_failed_count')::bigint=(health->>'write_failed_count')::bigint+1;
 assert public.s2a_log_health()->>'last_error'='system_log_write_failed','diagnostics contain only a safe code';
 perform public.s2a_log_config_set(cfg||'{"enable_sampling":true,"sampling_initial":1,"sampling_thereafter":2}');
 delete from public.s2a_log_samples;
 health:=public.s2a_log_health();
 for n in 1..9 loop perform public.s2a_log_write(event);end loop;
 select sum(1+(count-1)/2) into expected from public.s2a_log_samples;
 assert (public.s2a_log_health()->>'written_count')::bigint-(health->>'written_count')::bigint=expected,'sampling applies across invocations';
 assert (public.s2a_log_health()->>'dropped_count')::bigint-(health->>'dropped_count')::bigint=9-expected;
 assert public.s2a_log_health()->>'queue_depth'='0';
 assert public.s2a_log_health()->>'queue_capacity'='0','direct DB writes do not pretend to have a queue';
 assert (public.s2a_log_cleanup(jsonb_build_object('request_id',rid))->>'deleted')::integer=2+expected;
 begin perform public.s2a_log_cleanup('{}');raise exception 'empty filter accepted';exception when raise_exception then assert sqlerrm='OPS_SYSTEM_LOG_CLEANUP_FILTER_REQUIRED';end;
 begin perform public.s2a_log_cleanup('{"typo":"x"}');raise exception 'unknown filter accepted';exception when raise_exception then assert sqlerrm='invalid_log_filter';end;

 perform public.s2a_log_config_set(cfg||'{"persist_access_logs":true}');
 insert into auth.users(id) values(actor);
 insert into public.s2a_groups(id,name) values(gid,'Ops logging fixture');
 insert into public.s2a_memberships(user_id,group_id) values(actor,gid);
 insert into public.s2a_accounts(id,name,group_id,account_fingerprint,ciphertext,iv) values(aid,'Ops account',gid,'ops-logging-fixture','encrypted','iv');
 insert into public.s2a_keys(user_id,group_id,name,key_hash,key_prefix) values(actor,gid,'Ops key',repeat('d',64),'ops-key');
 perform public.s2a_wallet_update(actor,1,'set');
 lease:=(public.s2a_acquire(repeat('d',64),'gpt-4.1',gen_random_uuid(),'{}',true,null,'{}')->>'lease_id')::uuid;
 assert lease is not null;
 perform public.s2a_finish(lease,200,'completed',100,10,0,0);
 select w.balance into wallet_balance from public.s2a_wallets w where user_id=actor;
 assert wallet_balance<1;
 assert (select count(*)=1 from public.s2a_system_logs where account_id=aid and user_id=actor and message='request_completed' and platform='openai'),'gateway settlement records actual account metadata';
 update public.s2a_usage set created_at=now()-interval '40 days' where id=lease;
 update public.s2a_system_logs set created_at=now()-interval '40 days' where account_id=aid;
 select count(*) into usage_count from public.s2a_usage where id=lease;
 perform public.s2a_log_retention();
 assert (select count(*)=usage_count from public.s2a_usage where id=lease),'zero request retention preserves usage';
 assert not exists(select 1 from public.s2a_system_logs where account_id=aid),'old logs expire';
 perform public.s2a_log_config_set(cfg||'{"request_retention_days":1}');
 perform public.s2a_log_retention();
 assert not exists(select 1 from public.s2a_usage where id=lease),'positive retention expires old requests';
 perform public.s2a_finish(lease,200,'completed',100,10,0,0);
 assert (select w.balance=wallet_balance from public.s2a_wallets w where user_id=actor),'usage expiry never permits another charge';
 assert (select count(*)=1 from public.s2a_wallet_ledger where user_id=actor and reason='usage'),'ledger survives expiry';
 assert (select usage_5h>0 from public.s2a_keys where user_id=actor),'spend windows survive usage expiry';
 assert not has_table_privilege('anon','public.s2a_system_logs','select');
 assert not has_table_privilege('authenticated','public.s2a_log_runtime','select');
 assert not has_table_privilege('service_role','public.s2a_system_logs','delete');
 assert not has_function_privilege('authenticated','public.s2a_log_write(jsonb)','execute');
 assert not has_function_privilege('service_role','public.s2a_log_retention()','execute');
 assert has_function_privilege('service_role','public.s2a_log_config_set(jsonb)','execute');
end $$;
rollback;
