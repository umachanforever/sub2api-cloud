begin;
do $$
declare a jsonb;b jsonb;v jsonb;aid bigint;bid bigint;ts timestamptz;patch jsonb;r public.s2a_ops_alert_rules;expired_count float8;soon_count float8;selected_account uuid:=gen_random_uuid();proxy_group uuid:=gen_random_uuid();
begin
 patch:='{"name":"Proxy","protocol":"socks5h","host":"proxy.example.com","port":1080,"ciphertext":"YWJjZGVmZ2hpamtsbW5vcHFyc3Q=","iv":"YWJjZGVmZ2hpamts","fingerprint":"aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa"}';
 a:=public.s2a_proxy_save(null,patch);assert not a?'error';aid:=(a->>'id')::bigint;
 b:=public.s2a_proxy_save(null,patch,null,true);assert b->'reused'='true';assert b->>'id'=a->>'id';
 v:=public.s2a_proxy_read(aid);assert jsonb_array_length(v->'items')=1;assert v->'items'->0->>'account_count'='0';
 select updated_at into ts from public.s2a_proxies where id=aid;
 v:=public.s2a_proxy_save(aid,'{"name":"Renamed"}',ts);assert not v?'error';
 v:=public.s2a_proxy_save(aid,'{"name":"Stale"}',ts);assert v->>'error'='proxy_changed_retry';
 assert not public.s2a_proxy_probe_save(aid,ts,'{"success":false,"message":"ignored"}'),'old probe cannot overwrite edited configuration';
 insert into public.s2a_groups(id,name,require_privacy_set) values(proxy_group,'Proxy registry fixture',false);
 insert into public.s2a_accounts(id,name,group_id,platform,type,account_fingerprint,ciphertext,iv) values(selected_account,'Bound proxy account',proxy_group,'openai','apikey',selected_account::text,'fixture','fixture');
 update public.s2a_accounts set proxy_id=aid where id=selected_account;
 assert public.s2a_proxy_read(aid)->'items'->0->>'account_count'='1','proxy binding count must update';
 v:=public.s2a_proxy_delete(array[aid]);assert v->'skipped'->0->>'reason'='proxy_in_use';
 update public.s2a_accounts set proxy_id=null where id=selected_account;
 select updated_at into ts from public.s2a_proxies where id=aid;
 v:=public.s2a_proxy_save(aid,jsonb_build_object('fallback_mode','proxy','backup_proxy_id',aid),ts);assert v->>'error'='proxy_fallback_cycle';
 b:=public.s2a_proxy_save(null,patch||'{"name":"Backup","fallback_mode":"proxy"}'||jsonb_build_object('backup_proxy_id',aid));bid:=(b->>'id')::bigint;assert bid is not null;
 v:=public.s2a_proxy_save(aid,jsonb_build_object('fallback_mode','proxy','backup_proxy_id',bid),ts);assert v->>'error'='proxy_fallback_cycle';
 v:=public.s2a_proxy_delete(array[aid]);assert v->'skipped'->0->>'reason'='proxy_in_use';
 v:=public.s2a_proxy_delete(array[bid]);assert v->'deleted_ids'=jsonb_build_array(bid);
 r:=jsonb_populate_record(null::public.s2a_ops_alert_rules,'{"metric_type":"proxy_expired_count","filters":{}}');
 expired_count:=public.s2a_ops_alert_metric(r,now());
 update public.s2a_proxies set expires_at=now()-interval '1 second' where id=aid;
 assert public.s2a_ops_alert_metric(r,now())=expired_count+1, 'expiry alert counts use the current registry';
 v:=public.s2a_proxy_read(aid,'{"status":"expired"}');assert v->>'total'='1';assert v->'items'->0->>'status'='expired';
 v:=public.s2a_proxy_read(aid,'{"status":"active"}');assert v->>'total'='0';
 r.metric_type:='proxy_expiring_soon_count';soon_count:=public.s2a_ops_alert_metric(r,now());
 update public.s2a_proxies set expires_at=now()+interval '1 day',expiry_warn_days=7 where id=aid;
 assert public.s2a_ops_alert_metric(r,now())=soon_count+1;
 update public.s2a_proxies set status='inactive' where id=aid;
 assert public.s2a_ops_alert_metric(r,now())=soon_count, 'inactive proxies do not trigger expiring-soon alerts';
 v:=public.s2a_proxy_delete(array[aid]);assert v->'deleted_ids'=jsonb_build_array(aid);
 assert not has_table_privilege('service_role','public.s2a_proxies','SELECT');
 assert not has_function_privilege('authenticated','public.s2a_proxy_read(bigint,jsonb,boolean)','EXECUTE');
end $$;
rollback;
